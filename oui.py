def vendor(mac: str) -> str:
    """Return the manufacturer name for the first three octets of a MAC address.

    Returns an empty string when the prefix is not present in the OUI database.
    """
    prefix = mac.lower()[:8]
    return OUI_DB.get(prefix, "")


def is_randomized(mac: str) -> bool:
    """Return True if the MAC address appears to have been randomly generated by the OS.

    iOS 14+, Android 10+, and Windows 10+ randomize MAC addresses by default,
    setting the locally-administered bit (bit 1 of the first byte). A randomized
    MAC has no real OUI, so vendor lookup will always return an empty string for it.
    """
    try:
        return bool(int(mac.split(":")[0], 16) & 0x02)
    except (ValueError, IndexError):
        return False
